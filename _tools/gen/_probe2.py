t("concat axis=1 inner", lambda: pd.concat([pd.DataFrame({"a": [1]}, index=[0]), pd.DataFrame({"b": [2]}, index=[1])], axis=1, join="inner").shape)
t("concat mismatched cols", lambda: pd.concat([pd.DataFrame({"a": [1]}), pd.DataFrame({"b": [2]})]).isna().sum().to_dict())
t("df.join how=outer lsuffix", lambda: pd.DataFrame({"v": [1]}, index=[1]).join(pd.DataFrame({"v": [2]}, index=[2]), how="outer", lsuffix="_l", rsuffix="_r").shape)
t("isin semi join", lambda: L[L["k"].isin(R["k"])].shape)

